#!/usr/bin/env node
// Regenerate crates/pzprst/src/variety_table.rs from pzprjs's variety list.
//
//   node tools/gen_variety.js [--pzprjs ../pzprjs]
"use strict";

const fs = require("fs");
const path = require("path");
const { execSync } = require("child_process");

const ROOT = path.resolve(__dirname, "..");
const args = process.argv.slice(2);
const i = args.indexOf("--pzprjs");
const PZPRJS = path.resolve(i >= 0 ? args[i + 1] : process.env.PZPRJS || path.join(ROOT, "../pzprjs"));
const pzpr = require(path.join(PZPRJS, "dist/js/pzpr.js"));
const COMMIT = execSync("git rev-parse HEAD", { cwd: PZPRJS }).toString().trim();

const rows = [];
for (const pid of Object.keys(pzpr.variety.info)) {
	const info = pzpr.variety.info[pid];
	const aliases = Object.values(info.alias).filter((a) => typeof a === "string");
	rows.push(
		"    (" + JSON.stringify(pid) + ", " + JSON.stringify(info.urlid) + ", &[" +
			aliases.map((a) => JSON.stringify(a)).join(", ") + "]),"
	);
}

const out =
	"// @generated by tools/gen_variety.js from pzprjs " + COMMIT + ". Do not edit.\n\n" +
	"pub const PZPRJS_COMMIT: &str = " + JSON.stringify(COMMIT) + ";\n\n" +
	"/// (pid, urlid, aliases) in pzprjs declaration order; alias lookup takes the first match.\n" +
	"pub static VARIETIES: &[(&str, &str, &[&str])] = &[\n" + rows.join("\n") + "\n];\n";
fs.writeFileSync(path.join(ROOT, "crates/pzprst/src/variety_table.rs"), out);
console.log(rows.length + " varieties");
