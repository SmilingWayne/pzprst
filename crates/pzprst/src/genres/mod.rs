//! Genre plug-ins: one module per pzprjs variety file.

use crate::board::Board;
use crate::error::{Diagnostics, Result};
use crate::fileio::{FileReader, FileWriter};
use crate::transform::Transform;

pub(crate) trait Genre: Sync {
    fn pid(&self) -> &'static str;
    /// pzprjs `Board.hasborder`.
    fn hasborder(&self) -> u8;
    /// URL pflag character and FileIO flag line ↔ pzprjs config key.
    fn rule_flags(&self) -> &'static [(char, &'static str)];
    /// `decodePzpr`; returns the unconsumed body.
    fn decode_url(&self, b: &mut Board, body: &str, d: &mut Diagnostics) -> String;
    /// `encodePzpr` body (flags are written by the caller).
    fn encode_url(&self, b: &Board) -> Result<String>;
    /// `FileIO.decodeData`.
    fn decode_fileio(&self, r: &mut FileReader, b: &mut Board, d: &mut Diagnostics) -> Result<()>;
    /// `FileIO.encodeData`; sets `w.filever`.
    fn encode_fileio(&self, b: &Board, w: &mut FileWriter) -> Result<()>;
    /// Value-range and URL-representability checks for data that did not come from a URL.
    fn validate(&self, b: &Board, d: &mut Diagnostics);
    /// Symmetries that preserve puzzle meaning.
    fn symmetries(&self) -> &'static [Transform] {
        &Transform::ALL
    }
    /// pzprjs `BoardExec.adjustBoardData`: directional content adjusted
    /// **before** the coordinates move (pzprjs calls it once per board
    /// operation, so a composed transform must apply the operations in
    /// `tools/gen_fixtures.js` order: rot90 = TURNR, transpose = TURNL+FLIPY, …).
    fn adjust_board_data_before(&self, _t: Transform, _b: &mut Board) {}

    /// pzprjs `BoardExec.adjustBoardData2`: the same, **after** the coordinates
    /// have moved, on the transformed board.
    fn adjust_board_data(&self, _t: Transform, _b: &mut Board) {}
}

// `mod g_<pid>;` for every src/genres/<pid>.rs and `static GENRES`, generated by build.rs.
include!(concat!(env!("OUT_DIR"), "/genres.rs"));

pub(crate) fn get(pid: &str) -> Option<&'static dyn Genre> {
    GENRES.iter().copied().find(|g| g.pid() == pid)
}

/// pzprjs pids that pzprst can read and write, sorted.
pub fn supported() -> Vec<&'static str> {
    GENRES.iter().map(|g| g.pid()).collect()
}
